import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parseHTML } from 'linkedom';
import { indexedDatabase } from './test-support/indexed-db.mjs';
import { createSchemeStorage, APPLIED_SCHEME_KEY } from './scheme-storage.mjs';
import { createSchemeModel } from './scheme-model.mjs';
import { navigateRegion } from './test-support/editor-navigation.mjs';

const tick = () => new Promise(resolve => setImmediate(resolve));

test('apply survives reload independently of saved draft; explicit exit clears application', async () => {
  const { factory, controls } = indexedDatabase();
  const draft = createSchemeStorage({ indexedDB: factory });
  const applied = createSchemeStorage({ indexedDB: factory, key: APPLIED_SCHEME_KEY });
  const { validate, base } = createSchemeModel();
  await draft.save(JSON.stringify(validate({ ...base, template: 'jinghai', bodyWeight: 400 })));
  let generation = 0;
  async function boot() {
    const { document, window } = parseHTML('<html><head><style id="custom-style"></style></head><body><div id="extensions_settings"></div><div id="sheld"><div id="chat"></div></div></body></html>');
    const descriptor = Object.getOwnPropertyDescriptor(window.HTMLSelectElement.prototype, 'value');
    Object.defineProperty(window.HTMLSelectElement.prototype, 'value', { get: descriptor.get, set(value) { for (const option of this.options) option.toggleAttribute('selected', option.value === String(value)); }, configurable: true });
    const values = new Map();
    Object.assign(globalThis, { document, window, indexedDB: factory, localStorage: { getItem: key => values.get(key), setItem: (key, value) => values.set(key, value) }, requestAnimationFrame: () => 1, cancelAnimationFrame: () => {}, ResizeObserver: class { observe() {} unobserve() {} disconnect() {} } });
    await import(`./index.js?application-test=${++generation}`);
    return { document, window, shadow: document.querySelector('#orange-theme-lab').shadowRoot };
  }
  let ui = await boot();
  assert.equal(ui.document.querySelector('#orange-theme-live-style'), null, 'saving alone does not activate');
  ui.shadow.querySelector('.launcher').click();
  assert.equal(ui.shadow.querySelector('[aria-label="基础模板"]'), null);
  controls.failNext = 'QuotaExceededError';
  ui.shadow.querySelector('#apply-live').click();
  await tick(); await tick();
  assert.equal(await applied.load(), null, 'failed apply does not persist');
  assert.match(ui.shadow.querySelector('#notice').textContent, /应用失败/);
  assert.ok(ui.document.querySelector('#orange-theme-live-style'), 'failed write keeps the editor preview');
  ui.shadow.querySelector('#apply-live').click();
  await tick(); await tick();
  assert.ok(await applied.load());
  assert.ok(ui.document.querySelector('#orange-theme-live-style'));
  assert.equal(ui.document.querySelector('#custom-style').disabled, true);
  await draft.save(JSON.stringify(validate({ ...base, bodyWeight: 700 })));
  ui.window.dispatchEvent(new ui.window.Event('pagehide'));
  assert.ok(await applied.load(), 'pagehide does not stop persistent application');
  ui = await boot();
  assert.ok(ui.document.querySelector('#orange-theme-live-style'), 'boot restores without opening editor');
  assert.equal(ui.document.querySelector('#custom-style').disabled, true);
  assert.equal(JSON.parse(await applied.load()).bodyWeight, 400, 'later saves do not change applied snapshot');
  assert.equal(JSON.parse(await draft.load()).bodyWeight, 700);
  ui.shadow.querySelector('.launcher').click();
  assert.equal(ui.shadow.querySelector('[aria-label="基础模板"]'), null);
  ui.shadow.querySelector('#apply-live').click();
  await tick(); await tick();
  controls.failNext = 'QuotaExceededError';
  ui.document.querySelector('[data-workshop-action="stop"]').click();
  await tick(); await tick();
  assert.ok(await applied.load(), 'failed stop retains the application');
  assert.ok(ui.document.querySelector('#orange-theme-live-style'));
  ui.document.querySelector('[data-workshop-action="stop"]').click();
  await tick(); await tick();
  assert.equal(await applied.load(), null);
  assert.equal(ui.document.querySelector('#orange-theme-live-style'), null);
  assert.equal(ui.document.querySelector('#custom-style').disabled, false);
  ui.window.dispatchEvent(new ui.window.Event('pagehide'));
  ui = await boot();
  assert.equal(ui.document.querySelector('#orange-theme-live-style'), null);
  ui.shadow.querySelector('.launcher').click();
  ui.shadow.querySelector('#apply-live').click();
  await tick(); await tick();
  const appliedCss = ui.document.querySelector('#orange-theme-live-style').textContent;
  const appliedJson = await applied.load();
  ui.shadow.querySelector('.launcher').click();
  navigateRegion(ui.shadow, 'body');
  const size = ui.shadow.querySelector('[aria-label="正文字号 数值"]');
  size.value = '26';
  size.dispatchEvent(new ui.window.Event('input'));
  size.dispatchEvent(new ui.window.Event('change'));
  ui.shadow.querySelector('#save').click();
  await tick(); await tick();
  assert.equal(JSON.parse(await draft.load()).fontSize, 26, 'editing changed the draft independently');
  ui.shadow.querySelector('#close').click();
  await tick(); await tick();
  assert.equal(await applied.load(), appliedJson, 'exit editing preserves applied theme');
  assert.equal(ui.document.querySelector('#orange-theme-live-style').textContent, appliedCss, 'closing discards preview styling, not the applied snapshot');
  assert.ok(ui.document.querySelector('#orange-theme-live-style'));
  assert.equal(ui.document.querySelector('[data-workshop-action=stop]').hidden, false);
  ui.document.querySelector('[data-workshop-action=stop]').click();
  await tick(); await tick();
  assert.equal(await applied.load(), null, 'only the explicit stop action clears application');
  assert.equal(ui.document.querySelector('#orange-theme-live-style'), null);
  assert.equal(JSON.parse(await draft.load()).bodyWeight, 700, 'stop leaves saved draft intact');
});
