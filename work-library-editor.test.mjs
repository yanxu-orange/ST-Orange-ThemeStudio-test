import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parseHTML } from 'linkedom';
import { editorStorage, saveEditorScheme } from './test-support/editor-storage.mjs';
import { navigateRegion } from './test-support/editor-navigation.mjs';
import { createCustomWorkStorage } from './custom-work-storage.mjs';
import { createSchemeStorage, APPLIED_SCHEME_KEY } from './scheme-storage.mjs';
const settle = async () => { for (let i = 0; i < 6; i++) await new Promise(resolve => setImmediate(resolve)); };

test('named works open and save independently without replacing the saved draft or application', async () => {
  const { document, window } = parseHTML('<html><head><style id="custom-style"></style></head><body><div id="sheld"><div id="chat"></div></div></body></html>');
  const descriptor = Object.getOwnPropertyDescriptor(window.HTMLSelectElement.prototype, 'value');
  Object.defineProperty(window.HTMLSelectElement.prototype, 'value', { get: descriptor.get, set(value) { for (const option of this.options) option.toggleAttribute('selected', option.value === String(value)); }, configurable: true });
  const values = new Map();
  Object.assign(globalThis, { document, window, localStorage: { getItem: key => values.get(key), setItem: (key, value) => values.set(key, value) }, requestAnimationFrame: () => 1, cancelAnimationFrame: () => {}, ResizeObserver: class { observe() {} unobserve() {} disconnect() {} } });
  window.confirm = () => true;
  const draft = await editorStorage();
  await import('./index.js?work-library-editor');
  const shadow = document.querySelector('#orange-theme-lab').shadowRoot;
  const click = selector => { const element = shadow.querySelector(selector); assert.ok(element, selector); element.click(); };
  const changeSize = value => { navigateRegion(shadow, 'body'); const input = shadow.querySelector('[aria-label="正文字号 数值"]'); input.value = String(value); input.dispatchEvent(new window.Event('input')); input.dispatchEvent(new window.Event('change')); };
  const newWork = async name => { shadow.querySelector('[aria-label="新作品名称"]').value = name; click('[data-work-library="save-new"]'); await settle(); };
  click('.launcher');
  const savedBefore = await saveEditorScheme(shadow, draft);
  changeSize(21);
  click('#open-work-library'); await settle(); click('[data-work-tab="custom"]'); await settle(); await newWork('我的第一份');
  const works = createCustomWorkStorage();
  const first = (await works.list())[0]; assert.equal(JSON.parse(await works.load(first.id)).fontSize, 21);
  assert.deepEqual(JSON.parse(await draft.load()), savedBefore, 'saving a work does not overwrite the saved draft');
  assert.equal(await createSchemeStorage({ key: APPLIED_SCHEME_KEY }).load(), null, 'saving a work does not apply it');
  click('[data-work-library="close"]'); changeSize(26);
  click('[aria-label="打开工坊首页"]'); click('[data-flow="library"]'); await settle(); await newWork('我的第二份');
  assert.equal((await works.list()).length, 2);
  click(`[data-work-id="${first.id}"] [data-work-action="open"]`); await settle();
  assert.equal((await saveEditorScheme(shadow, draft)).fontSize, 21);
  assert.equal(shadow.querySelector('#save').textContent, '保存草稿');
  changeSize(24);
  assert.equal((await saveEditorScheme(shadow, draft)).fontSize, 24);
  assert.equal(JSON.parse(await works.load(first.id)).fontSize, 21, 'saving a changed draft never silently overwrites the opened named work');
  changeSize(21);
  click('#open-work-library'); await settle();
  click(`[data-work-id="${first.id}"] [data-work-action="delete"]`); await settle();
  assert.equal(await works.load(first.id), null); assert.equal((await works.list()).length, 1);
  click('[data-work-library="close"]');
  assert.equal((await saveEditorScheme(shadow, draft)).fontSize, 21, 'deleting a library entry does not delete its open draft');
  click('#close');
});
