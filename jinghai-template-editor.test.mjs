 click(`[data-work-id="${workId}"] [data-work-action="open"]`);
 for(let i=0;i<6;i++)await new Promise(resolve=>setImmediate(resolve));
 assert.deepEqual(await save(),selected);
 click('[aria-label="打开工坊首页"]');click('[data-flow="blank"]');
