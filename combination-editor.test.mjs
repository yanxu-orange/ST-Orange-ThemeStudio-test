import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parseHTML } from 'linkedom';
import { editorStorage, saveEditorScheme } from './test-support/editor-storage.mjs';
import { navigateRegion } from './test-support/editor-navigation.mjs';
import { createCustomWorkStorage } from './custom-work-storage.mjs';
import { combinationContext } from './combination-context.mjs';
const settle = async () => { for(let i=0;i<12;i++) await new Promise(r=>setImmediate(r)); };
test('six combination entrances resolve by current editing scope',()=>{
  for(const region of ['header','footer','input','topbar']) assert.equal(combinationContext({mode:'edit',page:'chat',region}).region,region);
  assert.equal(combinationContext({mode:'edit',page:'home',region:'page-header'}).region,'home');
  assert.equal(combinationContext({mode:'edit',page:'settings',region:'page-header'}).region,'page');
  assert.equal(combinationContext({mode:'edit',page:'chat',region:'body'}),null);
  assert.equal(combinationContext({mode:'library',page:'chat',region:'header'}),null);
});
test('saving and applying a header combination stays local and supports undo',async()=>{
 const {document,window}=parseHTML('<html><head><style id="custom-style"></style></head><body><div id="sheld"><div id="chat"></div></div></body></html>');
 const descriptor=Object.getOwnPropertyDescriptor(window.HTMLSelectElement.prototype,'value');
 Object.defineProperty(window.HTMLSelectElement.prototype,'value',{get:descriptor.get,set(value){for(const option of this.options)option.toggleAttribute('selected',option.value===String(value));},configurable:true});
 const values=new Map();
 Object.assign(globalThis,{document,window,localStorage:{getItem:k=>values.get(k),setItem:(k,v)=>values.set(k,v)},requestAnimationFrame:()=>1,cancelAnimationFrame:()=>{},ResizeObserver:class{observe(){}unobserve(){}disconnect(){}}});window.confirm=()=>true;
 const draft=await editorStorage();await import('./index.js?combination-editor');
 const shadow=document.querySelector('#orange-theme-lab').shadowRoot;
 const click=selector=>{const element=shadow.querySelector(selector);assert.ok(element,selector);element.click();};
 click('.launcher');navigateRegion(shadow,'header');
 const initial=await saveEditorScheme(shadow,draft);
 click('#open-region-combinations');await settle();
 shadow.querySelector('[aria-label="组合名称"]').value='我的头像';click('[data-combo-action="save-current"]');await settle();
 const storage=createCustomWorkStorage({databaseName:'orange.theme-lab.combinations.header.v1'});
 const [item]=await storage.list();assert.equal(item.name,'我的头像');
 const combo=JSON.parse(await storage.load(item.id));assert.equal(combo.region,'header');assert.equal(combo.fontSize,undefined);
 click('[data-combo-action="close"]');navigateRegion(shadow,'body');
 const size=shadow.querySelector('[aria-label="正文字号 数值"]');size.value='23';size.dispatchEvent(new window.Event('input'));size.dispatchEvent(new window.Event('change'));
 navigateRegion(shadow,'header');
 const height=shadow.querySelector('[aria-label="头像区总高度 数值"]');assert.ok(height);height.value='210';height.dispatchEvent(new window.Event('input'));height.dispatchEvent(new window.Event('change'));
 const before=await saveEditorScheme(shadow,draft);assert.equal(before.fontSize,23);assert.equal(before.headerHeight,210);
 click('#open-region-combinations');await settle();click(`[data-combo-id="${item.id}"] [data-combo-action="apply"]`);await settle();
 const applied=await saveEditorScheme(shadow,draft);assert.equal(applied.fontSize,23);assert.equal(applied.headerHeight,initial.headerHeight);
 click('#undo');const undone=await saveEditorScheme(shadow,draft);assert.deepEqual(undone,before);
 click('#close');
});
